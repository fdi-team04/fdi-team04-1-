def themes_of(title):
    t = str(title or ""); out = []
    for k, (_, words, _) in THEMES.items():
        hits = [w for w in words if w in t]
        if not hits or (_EX[k] and _EX[k].search(t)):
            continue
        if k in _REQ and all(h in _REQ[k][0] for h in hits) and not _REQ[k][1].search(t):
            continue
        out.append(k)
    return out

